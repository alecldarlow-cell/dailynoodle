let ending=false;
function finish(){
  if(!R||ending)return;ending=true;
  const p=score(R),b=R.z.filter(z=>z===0).length,t=today();
  const rec={p,b,z:R.z.slice(),g:R.g.slice(),secs:Math.round(R.secs||0)};
  const kept=window.dnCore.putDone(KEY,P.id,rec);          // the first result per puzzle stands
  // streak: a round finished on its own London day
  const s=save.streak||{last:null,n:0,best:0};
  if(P.date===t&&s.last!==t){s.n=s.last===dayBefore(t)?(s.n||0)+1:1;s.last=t;s.best=Math.max(s.best||0,s.n);}
  save.streak=s;save.done[P.id]=kept||Object.assign(rec,{d:t});save.best=Math.max(+save.best||0,p);save.cur=null;persist();
  R=null;VR=null;
  showResult(save.done[P.id],true);
  SND.done();
}
function noteFor(rec){
  const b=rec.b,spot=rec.g.filter((g,i)=>Math.abs(g/P.qs[i].a-1)<0.005).length;
  if(b===NQ)return '<strong>Ten bullseyes.</strong> Perfect.';
  if(b>0)return '<strong>'+cap(W[b])+' bullseye'+(b>1?'s':'')+'</strong>'+(spot?', '+(spot===b?(b>1?'all':'and it was'):(spot===1?'one of them':W[spot]+' of them'))+' spot on.':'.');
  let best=Infinity;rec.g.forEach((g,i)=>{const a=P.qs[i].a,k=Math.max(g/a,a/g);if(k<best)best=k;});
  return 'No bullseyes today. Your closest was '+Math.ceil((best-1)*100-1e-6)+'% out.';
}
