/* the win beat, as Mini, Doku, Redact and Tumbler pause before their sheets: the squares pop and turn
   green left to right (all at once: never letter by letter during play), a short hold, then the sheet */
function winBeat(done){
  if(REDUCE_MOTION){squares.forEach(c=>c.classList.add("won"));done();return;}
  const STEP=90,POP=520,HOLD=300;
  squares.forEach((c,k)=>{c.style.animationDelay=STEP*k+"ms";c.classList.add("pop");setTimeout(()=>c.classList.add("won"),STEP*k+POP*0.35);});
  const end=STEP*(N-1)+POP;
  setTimeout(()=>squares.forEach(c=>{c.classList.remove("pop");c.style.animationDelay="";c.classList.add("won");}),end);
  setTimeout(done,end+HOLD);
}
