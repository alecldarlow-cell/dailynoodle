#!/usr/bin/env node
'use strict';
/* One editable helper, bundled into existing entry points. No additional
   script request or dependency on a separately cached/offline file. */
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const TARGETS=['mini','doku','sweep','path','link','tangle','borders','reckon','finish','house'].map(t=>'engines/'+t+'.js')
 .concat(['front.js','dn-board.js','sw.js']);
const BLOCK=/\/\* dn-core:start \(generated by tools\/sync-core\.js\) \*\/[\s\S]*?\/\* dn-core:end \*\/\n/;
function bundled(src,core){
 const clean=src.replace(BLOCK,'');
 const banner=clean.match(/^\/\* Digi Puzzles — [\s\S]*?\*\/\n/);
 const at=banner?banner[0].length:0;
 return clean.slice(0,at)+'/* dn-core:start (generated by tools/sync-core.js) */\n'+core.trimEnd()+'\n/* dn-core:end */\n'+clean.slice(at);
}
function sync(check=false){
 const core=fs.readFileSync(path.join(ROOT,'dn-core.js'),'utf8'),changed=[];
 for(const file of TARGETS){
  const full=path.join(ROOT,file),src=fs.readFileSync(full,'utf8'),next=bundled(src,core);
  if(src!==next){changed.push(file);if(!check)fs.writeFileSync(full,next);}
 }
 if(check&&changed.length)throw Error('Shared helper copies are stale: '+changed.join(', ')+'. Run node tools/sync-core.js.');
 return changed;
}
module.exports={TARGETS,bundled,sync};
if(require.main===module){try{console.log('Shared helpers: '+sync(process.argv.includes('--check')).length+' copies updated/needed.');}catch(e){console.error(e.message);process.exitCode=1;}}
