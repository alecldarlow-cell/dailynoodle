#!/usr/bin/env node
'use strict';
// Bundle shared card markup into the existing front.js request.
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const BLOCK=/\/\* dn-cards:start \(generated by tools\/sync-cards\.js\) \*\/[\s\S]*?\/\* dn-cards:end \*\/\n/;
function bundled(front,renderer){
 const clean=front.replace(BLOCK,''),marker='/* dn-core:end */\n',at=clean.indexOf(marker);
 if(at<0)throw Error('sync-cards: shared core marker missing');
 const pos=at+marker.length;
 return clean.slice(0,pos)+'/* dn-cards:start (generated by tools/sync-cards.js) */\n'+renderer.trimEnd()+'\n/* dn-cards:end */\n'+clean.slice(pos);
}
function sync(check=false){
 const file=path.join(ROOT,'front.js'),src=fs.readFileSync(file,'utf8'),next=bundled(src,fs.readFileSync(path.join(__dirname,'card-renderer.js'),'utf8'));
 if(src===next)return false;
 if(check)throw Error('Card renderer is stale. Run node tools/sync-cards.js.');
 fs.writeFileSync(file,next);return true;
}
module.exports={bundled,sync};
if(require.main===module){try{console.log('Shared cards: '+(sync(process.argv.includes('--check'))?'updated':'current'));}catch(e){console.error(e.message);process.exitCode=1;}}
